# tests/test_ch0_big_picture.py
"""Tests for Section 0.5: Big Picture of MikanOS Architecture Roadmap and Tech Stack Rationale."""

from pathlib import Path
import subprocess

from common.os_sim import (
    ArchitectureModule,
    ArchitecturePhase,
    MikanOSArchitectureRoadmap,
    TechStackComparison,
    TechStackFeature,
)


def test_architecture_phases_structure() -> None:
    """Verify the 7 evolutionary architectural phases of MikanOS."""
    phases = MikanOSArchitectureRoadmap.get_phases()
    assert len(phases) == 7

    expected_ranges = [(1, 5), (6, 7), (8, 10), (11, 14), (15, 18), (19, 23), (24, 30)]

    for phase, (expected_start, expected_end) in zip(phases, expected_ranges):
        assert isinstance(phase, ArchitecturePhase)
        assert phase.start_chapter == expected_start
        assert phase.end_chapter == expected_end
        assert len(phase.key_milestones) >= 4
        assert len(phase.core_data_structures) >= 3
        assert len(phase.hardware_targets) >= 1


def test_core_modules_and_dependencies() -> None:
    """Verify that core modules have acyclic, chronologically sound dependencies."""
    modules = MikanOSArchitectureRoadmap.get_core_modules()
    assert len(modules) >= 15

    module_map = {m.module_name: m for m in modules}

    for m in modules:
        assert isinstance(m, ArchitectureModule)
        assert m.chapter >= 1 and m.chapter <= 30
        assert m.layer in ["HAL", "KernelCore", "Subsystem", "Userland"]
        for dep in m.dependencies:
            assert dep in module_map, f"Dependency {dep} of {m.module_name} must exist"
            assert module_map[dep].chapter <= m.chapter, (
                f"Module {m.module_name} (Ch.{m.chapter}) cannot depend on later module {dep} (Ch.{module_map[dep].chapter})"
            )


def test_tech_stack_comparisons() -> None:
    """Verify tech stack comparisons and rationales for UEFI, x86-64, and C++."""
    fw_comps = TechStackComparison.get_firmware_comparison()
    uefi_scores = [f.score for f in fw_comps if "UEFI" in f.technology]
    bios_scores = [f.score for f in fw_comps if "Legacy BIOS" in f.technology]
    assert sum(uefi_scores) > sum(bios_scores)

    arch_comps = TechStackComparison.get_architecture_comparison()
    x64_scores = [a.score for a in arch_comps if "x86-64" in a.technology]
    x86_scores = [a.score for a in arch_comps if "32-bit" in a.technology]
    assert sum(x64_scores) > sum(x86_scores)

    lang_comps = TechStackComparison.get_language_comparison()
    cpp_scores = [c.score for c in lang_comps if "C++" in c.technology]
    c_scores = [c.score for c in lang_comps if "C言語" in c.technology]
    assert sum(cpp_scores) > sum(c_scores)

    radar_metrics = TechStackComparison.get_radar_metrics()
    assert "UEFI (EDK II)" in radar_metrics
    assert "C++ (C++17/20)" in radar_metrics
    assert len(radar_metrics["UEFI (EDK II)"]) == 5


def test_cpp20_os_architecture_roadmap_execution() -> None:
    """Verify host execution of C++20 architecture roadmap and tech evaluation binary."""
    repo_root = Path(__file__).resolve().parent.parent
    bin_path = repo_root / "build" / "bin" / "ch00_os_architecture_roadmap"

    if not bin_path.exists():
        subprocess.run(["cmake", "-B", "build", "-S", "."], cwd=repo_root, check=True)
        subprocess.run(["cmake", "--build", "build"], cwd=repo_root, check=True)

    result = subprocess.run([str(bin_path)], capture_output=True, text=True, check=True)
    assert "[PASS] All 0.5 MikanOS Architecture Roadmap" in result.stdout
    assert "Seven Evolutionary Phases" in result.stdout
    assert "Module Dependency Graph" in result.stdout


